        public static string Get(string key) => RussianMessages[key];
        public static string Get(string key, params object[] values) => string.Format(Russian, Get(key), values);
        public static string QualityName(string name) =>
            RussianMessages.TryGetValue("settings.quality." + name, out var translation) ? translation : name;

        public static string Coins(long amount) => amount.ToString("N0", Russian) + " " + CoinForm(amount);

        public static string MissingCoins(long amount)
        {
            var singular = amount % 10 == 1 && amount % 100 != 11;
            var unit = Get(singular ? "number.coins.genitiveOne" : "number.coins.many");
            return Get("market.needCoins", amount.ToString("N0", Russian) + " " + unit);
        }

        private static string CoinForm(long amount)
        {
            var tens = System.Math.Abs(amount % 100);
            var ones = tens % 10;
            if (tens >= 11 && tens <= 14) return Get("number.coins.many");
            if (ones == 1) return Get("number.coins.one");
            return ones >= 2 && ones <= 4 ? Get("number.coins.few") : Get("number.coins.many");
        }

        public static string Duration(float seconds)
        {
            var tenths = UnityEngine.Mathf.RoundToInt(seconds * 10);
            if (tenths < 600) return Get("number.seconds", tenths / 10f);
            var rounded = UnityEngine.Mathf.RoundToInt(tenths / 10f);
            var minutes = rounded / 60;
            var rest = rounded % 60;
            return rest == 0 ? Get("number.minutes", minutes) : Get("number.minutesSeconds", minutes, rest);
        }
