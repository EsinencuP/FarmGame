namespace MyLittleFarm.Core.Grid
{
    /// <summary>
    /// Описывает назначение клетки мира. Числовые значения стабильны, потому что записываются
    /// в файл сохранения как byte и не должны меняться между версиями игры.
    /// </summary>
    public enum CellType : byte
    {
        // Природные клетки задаются ассетами окружения при регистрации чанка.
        Grass = 0,
        Dirt = 1,
        Water = 2,
        Rock = 3,
        Sand = 4,

        // Фермерские состояния меняются игровыми действиями игрока.
        Tilled = 10,
        Planted = 11,
        Watered = 12,

        // Инфраструктурные состояния резервируют клетки под дороги и постройки.
        Road = 20,
        Building = 21,
        BuildingEdge = 22,
        // Деревья являются отдельным объектным слоем и блокируют клетку для прохода/строительства.
        Tree = 23,

        // Служебные значения запрещают взаимодействие с закрытым или незагруженным миром.
        Locked = 30,
        OutOfBounds = 31
    }
}
